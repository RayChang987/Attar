#!/usr/bin/env python3
"""docs/validation/timing_routing.md: Attar against OpenROAD / ORFS, from the JSON results the validation tools wrote.

  timing   tools/validate_sta.py (asap7, nangate45) and tools/validate_sta_ns3k.py: OpenSTA after estimate_parasitics
  sizing   tools/validate_sizing.py: random cell swaps, OpenROAD replace_cell then OpenSTA
  routing  tools/validate_gr.py: capacity against OpenROAD's congestion report, GROV against ORFS's global route
usage: make_validation_md.py [--sta J] [--ng45 J] [--ns3k J] [--sizing-asap7 J] [--sizing-ng45 J] [--gr J] [--out F]"""
import argparse
import json
import os
import statistics

import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
R = os.path.join(ROOT, 'orfs_runs')
INDEX = os.path.join(ROOT, 'zoo', 'index.json')


def cells(key):
    try:
        return json.load(open(INDEX))['designs'][key]['cells']
    except (OSError, KeyError):
        return None


def f(v, p='%.2f'):
    return '–' if v is None else p % v


def timing_table(rows, key_of):
    out = ['| design | cells | endpoints | WNS Attar / OpenSTA (ps) | WNS err | TNS err | setup MAE (ps) | hold MAE (ps) | '
           'setup Pearson | Attar run | OpenSTA |',
           '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |']
    for d, r in rows.items():
        c = cells(key_of(d))
        out.append('| %s | %s | %d | %.2f / %.2f | %s | %s | %.2f | %.2f | %.4f | %s | %.2f s |' % (
            d, '{:,}'.format(c) if c else '–', r['matched'], r['worst_ours'], r['worst_ref'],
            f(r.get('wns_err_pct'), '%.2f%%'), f(r.get('tns_err_pct'), '%.2f%%'), r['setup_mae'], r['hold_mae'],
            r['setup_pearson'], ('%.1f ms' % (1000 * r['attar_s'])) if r.get('attar_s') is not None else '–',
            r['ref_s']))
    return out


def ranks(x):
    o = sorted(range(len(x)), key=lambda i: x[i])
    r = [0.0] * len(x)
    i = 0
    while i < len(o):                                     # ties share their mean rank
        j = i
        while j + 1 < len(o) and x[o[j + 1]] == x[o[i]]:
            j += 1
        for k in range(i, j + 1):
            r[o[k]] = (i + j) / 2
        i = j + 1
    return r


def summary(rows):
    w = [r['wns_err_pct'] for r in rows.values() if r.get('wns_err_pct') is not None]
    t = [r['tns_err_pct'] for r in rows.values() if r.get('tns_err_pct') is not None]
    return ('%d designs; WNS error median %.2f%%, max %.2f%%; TNS error median %.2f%%, max %.2f%%; hold MAE max %.2f ps'
            % (len(rows), statistics.median(w), max(w), statistics.median(t), max(t),
               max(r['hold_mae'] for r in rows.values())))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--sta', default=os.path.join(R, 'sta', 'v17_bundle.json'))
    ap.add_argument('--ng45', default=os.path.join(R, 'sta', 'ng45_v3_bundle.json'))
    ap.add_argument('--ns3k', default=os.path.join(R, 'sta_ns3k', 'v6.json'))
    ap.add_argument('--sizing-asap7', default=os.path.join(R, 'sizing', 'asap7_v1.json'))
    ap.add_argument('--sizing-ng45', default=os.path.join(R, 'sizing', 'ng45_v1.json'))
    ap.add_argument('--gr', default=os.path.join(R, 'gr', 'v2.json'))
    ap.add_argument('--out', default=os.path.join(ROOT, 'docs', 'validation', 'timing_routing.md'))
    a = ap.parse_args()
    sta, ng, ns = json.load(open(a.sta)), json.load(open(a.ng45)), json.load(open(a.ns3k))
    sz7, szn, gr = json.load(open(a.sizing_asap7)), json.load(open(a.sizing_ng45)), json.load(open(a.gr))
    L = ['# Validation against OpenROAD / ORFS', '',
         'Generated by `tools/make_validation_md.py` from the validation tools\' JSON results. Errors are Attar against '
         'OpenROAD (OpenSTA for timing) on the same netlist, placement and inputs; WNS / TNS errors are |Attar - '
         'OpenSTA| / |OpenSTA| (empty: no violation to compare against). Attar times on one RTX 3080 Ti in double '
         'precision; OpenSTA times are estimate_parasitics -placement + the full timing update.', '',
         '## Summary', '',
         '| check | designs | agreement |', '| --- | ---: | --- |',
         '| Timing, ORFS asap7 | %d | %s |' % (len(sta), summary(sta).split('; ', 1)[1]),
         '| Timing, ORFS nangate45 | %d | %s |' % (len(ng), summary(ng).split('; ', 1)[1]),
         '| Timing, NS3K (Innovus kit, unbuffered netlists) | %d | %s |' % (len(ns), summary(ns).split('; ', 1)[1]),
         '| Sizing (random swaps), asap7 | %d | %s |' % (len(sz7), summary(sz7).split('; ', 1)[1]),
         '| Sizing (random swaps), nangate45 | %d | %s |' % (len(szn), summary(szn).split('; ', 1)[1])]
    cap = [abs(r[t]['capacity_err_%']) for r in gr.values() for t in r]
    fr = [r['fresh'] for r in gr.values() if 'fresh' in r]; sr = [r['stress'] for r in gr.values() if 'stress' in r]
    L.append('| GR capacity vs OpenROAD (fresh + stress) | %d | total capacity error max %.3f%%, exact on %d of %d |'
             % (len(gr), max(cap), sum(c == 0 for c in cap), len(cap)))
    L.append('| GROV, ORFS setting (ORFS routes all without overflow) | %d | Attar 0-%.2f%% vs ORFS 0-%.2f%% |'
             % (len(fr), max(r['attar_grov_%'] for r in fr), max(r['orfs_grov_%'] for r in fr)))
    L.append('| GROV, stress (layer adjustment 0.7) | %d | mean abs difference %.1f points; per-edge Pearson %.2f-%.2f |'
             % (len(sr), statistics.mean(abs(r['attar_grov_%'] - r['orfs_grov_%']) for r in sr),
                min(r['pearson'] for r in sr), max(r['pearson'] for r in sr)))
    ga, go = [r['attar_grov_%'] for r in sr], [r['orfs_grov_%'] for r in sr]
    L.append('| GROV ranking across designs, stress | %d | Pearson %.3f, Spearman %.3f of Attar\'s GROV with ORFS\'s |'
             % (len(sr), np.corrcoef(ga, go)[0, 1], np.corrcoef(ranks(ga), ranks(go))[0, 1]))
    L += ['', 'Notes: a TNS error is relative to OpenSTA\'s TNS, so it is large where that TNS is tiny (asap7 aes: '
          'Attar %.2f ps vs OpenSTA %.2f ps). NS3K netlists are unbuffered, so their slacks run to microseconds and the '
          'setup MAE in ps is large in absolute terms only.' % (sta['aes']['tns_ours'], sta['aes']['tns_ref'])]
    L += ['', '## Timing (STA)', '',
          'Setup / hold slack of every endpoint (register data pins, outputs) against OpenSTA after `estimate_parasitics '
          '-placement`, at the ORFS 3_3_place_gp placement (`tools/validate_sta.py`) or an Attar placement exported as '
          'DEF (NS3K, `tools/validate_sta_ns3k.py`).', '', '### ORFS asap7', '']
    L += timing_table(sta, lambda d: 'after_fp/orfs_asap7/' + d)
    L += ['', '### ORFS nangate45', '']
    L += timing_table(ng, lambda d: 'after_fp/orfs_nangate45/' + d)
    L += ['', '### NS3K', '']
    L += timing_table(ns, lambda d: 'after_fp/ns3k/' + d)
    L += ['', '## Sizing', '', 'A seeded random 20% of the cells with alternatives swapped within their equivalence '
          'class (drive strength, threshold voltage): `d.resize` in Attar (masters from the zoo\'s library bundle), '
          '`replace_cell` in OpenROAD, then both time the design (`tools/validate_sizing.py`).', '',
          '| design | platform | swaps | WNS err | TNS err | setup MAE (ps) | hold MAE (ps) | setup Pearson |',
          '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |']
    for plat, rows in (('asap7', sz7), ('nangate45', szn)):
        for d, r in rows.items():
            L.append('| %s | %s | %d | %s | %s | %.2f | %.2f | %.4f |' % (
                d, plat, r['swaps'], f(r.get('wns_err_pct'), '%.2f%%'), f(r.get('tns_err_pct'), '%.2f%%'),
                r['setup_mae'], r['hold_mae'], r['setup_pearson']))
    L += ['', '## Global routing (GROV)', '',
          '`d.gr_overflow()`: RUDY demand per gcell edge and direction against OpenROAD\'s gcell grid and edge '
          'capacities, GROV = share of gcell edges whose demand exceeds capacity. Truth: OpenROAD\'s capacity per layer '
          '(its congestion report) and its routed usage per edge after global routing (`write_global_route_segments`) '
          'of the placement ORFS routed, at ORFS\'s layer adjustment (fresh) and at 0.7 (stress) '
          '(`tools/validate_gr.py`). RUDY is demand before routing: the router\'s detours lower the overflow of '
          'mildly congested designs and spread that of heavily congested ones.', '',
          '| design | set | adjustment | capacity err (total / worst layer) | GROV Attar | GROV ORFS | ORFS total '
          'overflow | per-edge Pearson | top-5% hotspot recall |',
          '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |']
    for d, rr in gr.items():
        for t, r in rr.items():
            L.append('| %s | %s | %.2f | %.3f%% / %.3f%% | %.2f%% | %.2f%% | %d | %.3f | %.0f%% |' % (
                d, t, r['adjustment'], r['capacity_err_%'], r['capacity_worst_layer_%'], r['attar_grov_%'],
                r['orfs_grov_%'], r['orfs_total_overflow'], r['pearson'], 100 * r['hot5_recall']))
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, 'w') as fo:
        fo.write('\n'.join(L) + '\n')
    print('wrote', a.out)


if __name__ == '__main__':
    main()
