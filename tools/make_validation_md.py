#!/usr/bin/env python3
"""docs/validation/timing_routing.md: Attar against OpenROAD / ORFS, from the JSON results the validation tools wrote.

  timing   tools/validate_sta.py (asap7, nangate45), tools/validate_sta_ns3k.py, tools/validate_sta_iccad2015.py and
           tools/validate_iccad2025.py: OpenSTA after estimate_parasitics
  sizing   tools/validate_sizing.py: random cell swaps, OpenROAD replace_cell then OpenSTA
  routing  tools/validate_gr.py: capacity against OpenROAD's congestion report, GROV against ORFS's global route
usage: make_validation_md.py [--sta J] [--ng45 J] [--ns3k J] [--iccad2015 J] [--iccad2025 J] [--sizing-asap7 J] [--sizing-ng45 J]
                             [--gr J] [--out F]"""
import argparse
import json
import os
import statistics

import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
R = os.path.join(ROOT, 'orfs_runs')
INDEX = os.path.join(ROOT, 'zoo', 'index.json')


def cells(key):
    try:
        return json.load(open(INDEX))['designs'][key]['cells']
    except (OSError, KeyError):
        return None


def f(v, p='%.2f'):
    return '–' if v is None else p % v


def timing_table(rows, key_of):
    out = ['| design | cells | endpoints | WNS Attar / OpenSTA (ps) | WNS err | TNS err | setup MAE (ps) | hold MAE (ps) | '
           'setup Pearson | Attar run | OpenSTA |',
           '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |']
    for d, r in rows.items():
        c = cells(key_of(d))
        out.append('| %s | %s | %d | %.2f / %.2f | %s | %s | %.2f | %.2f | %.4f | %s | %.2f s |' % (
            d, '{:,}'.format(c) if c else '–', r['matched'], r['worst_ours'], r['worst_ref'],
            f(r.get('wns_err_pct'), '%.2f%%'), f(r.get('tns_err_pct'), '%.2f%%'), r['setup_mae'], r['hold_mae'],
            r['setup_pearson'], ('%.1f ms' % (1000 * r['attar_s'])) if r.get('attar_s') is not None else '–',
            r['ref_s']))
    return out


def ranks(x):
    o = sorted(range(len(x)), key=lambda i: x[i])
    r = [0.0] * len(x)
    i = 0
    while i < len(o):                                     # ties share their mean rank
        j = i
        while j + 1 < len(o) and x[o[j + 1]] == x[o[i]]:
            j += 1
        for k in range(i, j + 1):
            r[o[k]] = (i + j) / 2
        i = j + 1
    return r


def summary(rows):
    w = [r['wns_err_pct'] for r in rows.values() if r.get('wns_err_pct') is not None]
    t = [r['tns_err_pct'] for r in rows.values() if r.get('tns_err_pct') is not None]
    return ('%d designs; WNS error median %.2f%%, max %.2f%%; TNS error median %.2f%%, max %.2f%%; hold MAE max %.2f ps'
            % (len(rows), statistics.median(w), max(w), statistics.median(t), max(t),
               max(r['hold_mae'] for r in rows.values())))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--sta', default=os.path.join(R, 'sta', 'v20_p0.json'))
    ap.add_argument('--ng45', default=os.path.join(R, 'sta', 'ng45_v6_p0.json'))
    ap.add_argument('--ns3k', default=os.path.join(R, 'sta_ns3k', 'v8_p0.json'))
    ap.add_argument('--iccad2015', default=os.path.join(R, 'sta_iccad2015', 'v3_early.json'))
    ap.add_argument('--iccad2025', default=os.path.join(R, 'iccad25_eval', 'v1.json'))
    ap.add_argument('--sizing-asap7', default=os.path.join(R, 'sizing', 'asap7_v2.json'))
    ap.add_argument('--sizing-ng45', default=os.path.join(R, 'sizing', 'ng45_v2.json'))
    ap.add_argument('--gr', default=os.path.join(R, 'gr', 'v2.json'))
    ap.add_argument('--edit', default=os.path.join(R, 'sta_ns3k_edit', 'edit_v2.json'))
    ap.add_argument('--debuffer-asap7', default=os.path.join(R, 'sta_def', 'asap7debuffer_v2.json'))
    ap.add_argument('--debuffer-ng45', default=os.path.join(R, 'sta_def', 'ng45debuffer_v2.json'))
    ap.add_argument('--out', default=os.path.join(ROOT, 'docs', 'validation', 'timing_routing.md'))
    a = ap.parse_args()
    sta, ng, ns = json.load(open(a.sta)), json.load(open(a.ng45)), json.load(open(a.ns3k))
    ic = json.load(open(a.iccad2015))
    i25 = json.load(open(a.iccad2025))
    for v in i25.values():                                 # the same columns as the other timing tables
        v.setdefault('worst_ours', v['wns']); v.setdefault('worst_ref', v['wns_ref'])
    sz7, szn, gr = json.load(open(a.sizing_asap7)), json.load(open(a.sizing_ng45)), json.load(open(a.gr))
    ed = json.load(open(a.edit))
    db7, dbn = json.load(open(a.debuffer_asap7)), json.load(open(a.debuffer_ng45))
    L = ['# Validation against OpenROAD / ORFS', '',
         'Generated by `tools/make_validation_md.py` from the validators\' JSON results. Attar against OpenROAD '
         '(OpenSTA for timing) on the same netlist, placement and inputs. WNS / TNS error = |Attar - OpenSTA| / '
         '|OpenSTA| (–: no violation). Attar runs on one RTX 3080 Ti in double precision; OpenSTA time is '
         '`estimate_parasitics -placement` plus the full timing update.', '',
         '## Summary', '',
         '| check | designs | agreement |', '| --- | ---: | --- |',
         '| Timing, ORFS asap7 | %d | %s |' % (len(sta), summary(sta).split('; ', 1)[1]),
         '| Timing, ORFS nangate45 | %d | %s |' % (len(ng), summary(ng).split('; ', 1)[1]),
         '| Timing, NS3K (Innovus kit, unbuffered netlists) | %d | %s |' % (len(ns), summary(ns).split('; ', 1)[1]),
         '| Timing, ICCAD 2015 superblue (Late and Early libraries) | %d | %s |' % (len(ic), summary(ic).split('; ', 1)[1]),
         '| Timing and power, ICCAD 2025 contest evaluation | %d | %s; power error max %.2f%% |'
         % (len(i25), summary(i25).split('; ', 1)[1], max(abs(e) for v in i25.values() for e in v['power_err_pct'])),
         '| Sizing (random swaps), asap7 | %d | %s |' % (len(sz7), summary(sz7).split('; ', 1)[1]),
         '| Sizing (random swaps), nangate45 | %d | %s |' % (len(szn), summary(szn).split('; ', 1)[1]),
         '| Netlist edits (buffers, clones), NS3K | %d | %s |' % (len(ed), summary(ed).split('; ', 1)[1]),
         '| Debuffer, asap7 | %d | %s |' % (len(db7), summary(db7).split('; ', 1)[1]),
         '| Debuffer, nangate45 | %d | %s |' % (len(dbn), summary(dbn).split('; ', 1)[1])]
    cap = [abs(r[t]['capacity_err_%']) for r in gr.values() for t in r]
    fr = [r['fresh'] for r in gr.values() if 'fresh' in r]; sr = [r['stress'] for r in gr.values() if 'stress' in r]
    L.append('| GR capacity vs OpenROAD (fresh + stress) | %d | total capacity error max %.3f%%, exact on %d of %d |'
             % (len(gr), max(cap), sum(c == 0 for c in cap), len(cap)))
    L.append('| GROV, ORFS setting (ORFS routes all without overflow) | %d | Attar 0-%.2f%% vs ORFS 0-%.2f%% |'
             % (len(fr), max(r['attar_grov_%'] for r in fr), max(r['orfs_grov_%'] for r in fr)))
    L.append('| GROV, stress (layer adjustment 0.7) | %d | mean abs difference %.1f points; per-edge Pearson %.2f-%.2f |'
             % (len(sr), statistics.mean(abs(r['attar_grov_%'] - r['orfs_grov_%']) for r in sr),
                min(r['pearson'] for r in sr), max(r['pearson'] for r in sr)))
    ga, go = [r['attar_grov_%'] for r in sr], [r['orfs_grov_%'] for r in sr]
    L.append('| GROV ranking across designs, stress | %d | Pearson %.3f, Spearman %.3f of Attar\'s GROV with ORFS\'s |'
             % (len(sr), np.corrcoef(ga, go)[0, 1], np.corrcoef(ranks(ga), ranks(go))[0, 1]))
    L += ['', 'TNS errors are relative, so they are large where OpenSTA\'s TNS is tiny. NS3K netlists are unbuffered: '
          'slacks reach microseconds, so their setup MAE is large only in absolute terms.']
    L += ['', '## Timing (STA)', '',
          'Setup and hold slack of every endpoint against OpenSTA after `estimate_parasitics -placement`, at ORFS\'s '
          '3_3_place_gp placement (`tools/validate_sta.py`) or, for NS3K, an Attar placement exported as DEF '
          '(`tools/validate_sta_ns3k.py`). Pins sit where OpenROAD puts them (the mean of the LEF rectangle centers). '
          'Endpoints only OpenSTA lists are unconstrained.',
          '', '### ORFS asap7', '']
    L += timing_table(sta, lambda d: 'after_fp/orfs_asap7/' + d)
    L += ['', '### ORFS nangate45', '']
    L += timing_table(ng, lambda d: 'after_fp/orfs_nangate45/' + d)
    L += ['', '### NS3K', '']
    L += timing_table(ns, lambda d: 'after_fp/ns3k/' + d)
    L += ['', '### ICCAD 2015 (superblue)', '',
          'Contest placement (`tools/validate_sta_iccad2015.py`); Late Liberty for setup (`-max`), Early for hold '
          '(`-min`); DREAMPlace 4.0 SDC; contest wire RC (2.535 ohm, 0.16 fF per um). Unconstrained endpoints (up to 4%) '
          'are not listed; every constrained one matches. The DEF drops the metal7-9 TRACKS, which the superblue LEF '
          'lacks.' + (' Run times: the Late-only run on an idle GPU (%s).' % next(iter(ic.values()))['times_from']
          if 'times_from' in next(iter(ic.values())) else ''), '']
    L += timing_table(ic, lambda d: 'after_fp/iccad2015/' + d)
    L += ['', '### ICCAD 2025 (contest evaluation)', '',
          'Problem C\'s scoring script (`openRoad_eval_script/eval_def.tcl`, `tools/validate_iccad2025.py`) at the given '
          'placement: the nldm libraries, the contest\'s `setRC.tcl`, `estimate_parasitics -placement`, then TNS, WNS '
          'and `report_power`; SRAM macros are black boxes. The SDCs include propagated clocks, tied pins, recovery / '
          'removal checks, latches and combinational loops. Power error: internal / switching / leakage.', '',
          '| design | cells | endpoints | WNS Attar / OpenSTA (ps) | WNS err | TNS err | setup MAE (ps) | hold MAE (ps) | '
          'power err (int / sw / leak) | Attar run | OpenSTA |',
          '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- | ---: | ---: |']
    for d, v in i25.items():
        c = cells('after_fp/iccad2025/' + d)
        L.append('| %s | %s | %d | %.2f / %.2f | %s | %s | %.2f | %.2f | %s | %.2f s | %.2f s |' % (
            d, '{:,}'.format(c) if c else '–', v['matched'], v['wns'], v['wns_ref'], f(v.get('wns_err_pct'), '%.2f%%'),
            f(v.get('tns_err_pct'), '%.2f%%'), v['setup_mae'], v['hold_mae'],
            ' / '.join('%+.2f%%' % e for e in v['power_err_pct']), v['attar_s'], v['ref_s']))
    L += ['', 'Attar run here is the first `d.timing()`, timer build included.']
    L += ['', '## Sizing', '', 'A seeded random 20% of the cells with alternatives are swapped within their '
          'equivalence class (drive strength, threshold voltage): `d.resize` in Attar, `replace_cell` in OpenROAD; then '
          'both time the design (`tools/validate_sizing.py`).', '',
          '| design | platform | swaps | WNS err | TNS err | setup MAE (ps) | hold MAE (ps) | setup Pearson |',
          '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |']
    for plat, rows in (('asap7', sz7), ('nangate45', szn)):
        for d, r in rows.items():
            L.append('| %s | %s | %d | %s | %s | %.2f | %.2f | %.4f |' % (
                d, plat, r['swaps'], f(r.get('wns_err_pct'), '%.2f%%'), f(r.get('tns_err_pct'), '%.2f%%'),
                r['setup_mae'], r['hold_mae'], r['setup_pearson']))
    n_ed = {k: sum(r['edits'][k] for r in ed.values()) for k in ('buffers', 'chained', 'clones', 'port_buffers')}
    L += ['', '## Netlist edits', '',
          'From each NS3K run\'s placement, `tools/validate_sta_ns3k.py --edit` (`edit_recipe`) adds a buffer on each '
          'signal net with 16 or more sinks (at most 200, the biggest first), a second buffer on 10 of those, clones of '
          'up to 50 cells with 4 or more loads and a buffer behind an input port, then runs `naive.legalize`; OpenSTA '
          'times the exported DEF. %d buffers (%d of them second ones), %d clones, %d behind ports, over %d designs.'
          % (n_ed['buffers'] + n_ed['chained'] + n_ed['port_buffers'], n_ed['chained'], n_ed['clones'],
             n_ed['port_buffers'], len(ed)), '']
    L += timing_table(ed, lambda d: 'after_fp/ns3k/' + d)
    nb = sum(r['edits']['buffers'] for r in list(db7.values()) + list(dbn.values()))
    ni = sum(r['edits']['inverters'] for r in list(db7.values()) + list(dbn.values()))
    L += ['', '### Debuffer', '',
          '`d.debuffer()` at ORFS\'s 3_3_place_gp placement removes the buffers and double inversions ORFS inserted '
          '(%d buffers, %d inverters over %d designs); OpenSTA times the exported DEF (`tools/validate_sta.py '
          '--debuffer`). The truth sets the run\'s routing layers (`set_routing_layers -signal`), which a DEF does not '
          'carry and on which `estimate_parasitics`\'s pin cut resistance depends.'
          % (nb, ni, len(db7) + len(dbn)), '', '#### asap7', '']
    L += timing_table(db7, lambda d: 'after_fp/orfs_asap7/' + d)
    L += ['', '#### nangate45', '']
    L += timing_table(dbn, lambda d: 'after_fp/orfs_nangate45/' + d)
    L += ['', '## Global routing (GROV)', '',
          '`d.gr_overflow()`: RUDY demand per gcell edge and direction against OpenROAD\'s gcell grid and edge '
          'capacities; GROV is the share of edges over capacity. Truth (`tools/validate_gr.py`): OpenROAD\'s capacity per '
          'layer and routed usage per edge (`write_global_route_segments`) on the placement ORFS routed, at ORFS\'s layer '
          'adjustment (fresh) and at 0.7 (stress). RUDY is demand before routing: detours lower mild overflow and spread '
          'heavy overflow.', '',
          '| design | set | adjustment | capacity err (total / worst layer) | GROV Attar | GROV ORFS | ORFS total '
          'overflow | per-edge Pearson | top-5% hotspot recall |',
          '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |']
    for d, rr in gr.items():
        for t, r in rr.items():
            L.append('| %s | %s | %.2f | %.3f%% / %.3f%% | %.2f%% | %.2f%% | %d | %.3f | %.0f%% |' % (
                d, t, r['adjustment'], r['capacity_err_%'], r['capacity_worst_layer_%'], r['attar_grov_%'],
                r['orfs_grov_%'], r['orfs_total_overflow'], r['pearson'], 100 * r['hot5_recall']))
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, 'w') as fo:
        fo.write('\n'.join(L) + '\n')
    print('wrote', a.out)


if __name__ == '__main__':
    main()
