#!/usr/bin/env python3
"""docs/validation/drv_power_cts.md from the validators' JSON results (orfs_runs/val/):
drv_<platform>.json (validate_drv.py), pwr_<platform>_<design>.json (validate_power.py), cts_asap7.json
(validate_cts.py), cts_engine.json (validate_cts_engine.py).
usage: make_drv_power_md.py [--out docs/validation/drv_power_cts.md]"""
import argparse
import glob
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
VAL = os.path.join(ROOT, 'orfs_runs', 'val')


def f(v, p='%.2f'):
    return '–' if v is None else p % v


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(ROOT, 'docs', 'validation', 'drv_power_cts.md'))
    a = ap.parse_args()
    L = ['# Design rules, power and clock trees against OpenROAD', '',
         'Generated by `tools/make_drv_power_md.py` from the validators\' JSON results. The truth is OpenROAD in the '
         'ORFS image (OpenSTA 3.1.0 of OpenROAD\'s November 2026 tree) on the same netlist, placement and inputs, '
         'after `estimate_parasitics -placement`. Attar runs on one RTX 3080 Ti.', '']
    # -- DRV
    L += ['## Design rules (`d.drv()`)', '',
          '`report_check_types -max_slew -max_capacitance -max_fanout` for every checked pin '
          '(`tools/validate_drv.py`) at ORFS\'s 3_3 placement. Errors are on the slack; violations are Attar / '
          'OpenSTA / both.', '',
          '| platform | design | slew pins | slew err max (ps) | cap pins | cap err max (fF) | fanout pins | '
          'violations slew | cap | fanout |', '| --- | --- | ---: | ---: | ---: | ---: | ---: | --- | --- | --- |']
    for plat in ('asap7', 'ng45'):
        p = os.path.join(VAL, 'drv_%s.json' % plat)
        if not os.path.exists(p):
            continue
        for dn, r in json.load(open(p)).items():
            s, c, fo = r['slew'], r['capacitance'], r['fanout']
            v = lambda x: '%d/%d/%d' % (x['viol_ours'], x['viol_ref'], x['viol_both'])  # noqa: E731
            L.append('| %s | %s | %d | %s | %d | %s | %d | %s | %s | %s |' % (
                'nangate45' if plat == 'ng45' else plat, dn, s['matched'], f(s['slack_maxe'], '%.3f'), c['matched'],
                f(c['slack_maxe'], '%.3f'), fo['matched'], v(s), v(c), v(fo)))
    L += ['', 'Residual slew errors (a few ps on a handful of pins) sit on adder cells whose inputs are tied: the '
          'delay calculation\'s treatment of arcs into constant outputs is not fully matched yet.', '']
    # -- power
    L += ['## Power (`d.power()`)', '',
          '`report_power` and `report_power -instances` (`tools/validate_power.py`): activities propagated from the '
          'default input activity, internal, switching and leakage power per instance.', '',
          '| platform | design | total Attar / OpenSTA (W) | error | instance rel. error | Attar (s) | OpenSTA (s) |',
          '| --- | --- | --- | ---: | ---: | ---: | ---: |']
    for plat in ('asap7', 'ng45'):
        for p in sorted(glob.glob(os.path.join(VAL, 'pwr_%s_*.json' % plat))):
            for dn, r in json.load(open(p)).items():
                L.append('| %s | %s | %.4e / %.4e | %.2f%% | %.4f | %.2f | %.2f |' % (
                    'nangate45' if plat == 'ng45' else plat, dn, r['total_ours'][3], r['total_ref'][3],
                    r['total_err_pct'], r['total_inst_mae_rel'], r['attar_s'], r['ref_s']))
    # -- propagated clocks
    p = os.path.join(VAL, 'cts_asap7.json')
    if os.path.exists(p):
        L += ['', '## Propagated clocks and CRPR', '',
              'ORFS\'s own clock trees (TritonCTS, the 4_cts stage, `tools/orfs_run_cts.sh`) timed with '
              '`set_propagated_clock` (`tools/validate_cts.py`): `d.timing()` against OpenSTA\'s default (clock '
              'reconvergence pessimism removal on, `attar.timing.crpr`) and `d.timing(crpr=False)` against '
              '`sta::set_crpr_enabled 0`. Errors are per endpoint (ps); WNS / TNS Attar / OpenSTA; time is one '
              're-time with CRPR (without).', '',
              '| design | clock pins | arrival err max | endpoints | CRPR on: setup MAE / max | hold MAE / max | WNS | TNS '
              '| CRPR off: setup MAE / max | WNS | Attar ms |',
              '| --- | ---: | ---: | ---: | --- | --- | --- | --- | --- | --- | ---: |']
        for dn, r in json.load(open(p)).items():
            n0 = r['nocrpr']
            L.append('| %s | %s | %s | %d | %s / %s | %s / %s | %s / %s | %s / %s | %s / %s | %s / %s | %.0f (%.0f) |' % (
                dn, r.get('ck_matched'), f(r.get('ck_arrival_maxe'), '%.4f'), r['matched'], f(r['setup_mae'], '%.4f'),
                f(r.get('setup_maxe'), '%.3f'), f(r['hold_mae'], '%.4f'), f(r.get('hold_maxe'), '%.3f'),
                f(r['worst_ours']), f(r['worst_ref']), f(r['tns_ours'], '%.1f'), f(r['tns_ref'], '%.1f'),
                f(n0['setup_mae'], '%.4f'), f(n0.get('setup_maxe'), '%.3f'), f(min(n0['worst_ours'], 0)),
                f(min(n0['worst_ref'], 0)), 1e3 * r['attar_s'], 1e3 * r.get('attar_nocrpr_s', float('nan'))))
        L += ['', 'WNS here is the worst endpoint slack (positive when every endpoint meets timing). CRPR keeps, per '
              'data pin, the arrivals of every launch clock pin that can still be worst (OpenSTA\'s pruning) and '
              'credits each register check at the launch and capture clock paths\' last common pin; nothing is '
              'truncated, so the errors with CRPR are those of the timer without it.']
    # -- CTS engine
    eng = {}
    for p in sorted(glob.glob(os.path.join(VAL, 'cts_engine*.json'))):
        eng.update(json.load(open(p)))
    if eng:
        L += ['', '## Clock tree synthesis (`attar.naive.cts`)', '',
              'From ORFS\'s 3_5 placement (`tools/validate_cts_engine.py`). Agreement: OpenROAD reads the DEF Attar '
              'exports and times it (CRPR off and on). Quality: TritonCTS on the same placement, through ORFS\'s CTS steps '
              'without repair_timing; both measured by OpenSTA with CRPR on. Latency and spread: the latest register '
              'clock pin\'s arrival and the spread of all of them (ps); power in mW.', '',
              '| design | clock arrival err max | endpoint setup MAE (CRPR off / on) | Attar bufs / latency / spread / WNS / '
              'TNS / clock power | TritonCTS bufs / latency / spread / WNS / TNS / clock power |',
              '| --- | ---: | ---: | --- | --- |']
        for dn, r in eng.items():
            o, g, b = r['attar'], r['agreement'], r['triton']
            op = g['opensta']
            L.append('| %s | %s | %s / %s | %d / %.1f / %.1f / %.2f / %.1f / %.3f | %d / %.1f / %.1f / %.2f / %.1f / %.3f |'
                     % (dn, f(g['ck_max'], '%.4f'), f(g['setup_mae'], '%.4f'), f((g.get('crpr') or {}).get('setup_mae'), '%.4f'),
                        o['buffers'], o['latency'], o['spread'],
                        op['crpr_on']['wns'], op['crpr_on']['tns'], 1e3 * sum(o['power_clock']), b['buffers'][0],
                        b['latency'], b['spread'], b['crpr_on']['wns'], b['crpr_on']['tns'],
                        1e3 * b['power_clock'][3]))
    open(a.out, 'w').write('\n'.join(L) + '\n')
    print(a.out)


if __name__ == '__main__':
    main()
